"""Scaffold rubrics from the extracted answers and the question inventory.

This writes the parts of a rubric that can be derived mechanically -- marks, scenario
anchors, model answer, explanation -- and leaves `chains` empty for a human (or a
model reading the answer) to author. Nothing enters the bundle with
`reviewed: false`; that gate is the whole point (plan section 1f).

Chains are deliberately NOT generated by pattern-matching the model answer. A
keypoint is an ordered link in a cause-and-effect chain with a facet role, and
splitting prose on sentence boundaries produces plausible-looking rubrics that award
marks in the wrong places. A wrong rubric teaches a child wrong science with full
confidence, so the scaffold stays honestly empty until someone fills it in.

Scaffolding preserves any chains already authored: re-running never discards work.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from syllabus import (official_topics, out_of_scope_from_2026, themes_for,
                      unmapped)

REPO = Path(__file__).resolve().parent.parent
WORK_QUESTIONS = REPO / "work"
WORK_ANSWERS = REPO / "work-ans"
RUBRIC_DIR = REPO / "rubrics"

# Papers from 2023 onward follow the current syllabus; earlier ones do not and are
# tagged so the student can filter them out (CLAUDE.md section 5).
SYLLABUS_2023_FROM = 2023

FLAGS_FILE = REPO / "review" / "flags.json"


def flags_for(year: int) -> dict[str, dict]:
    """Rubrics flagged as wrong or doubtful.

    Rubrics are approved by default and this records the exceptions. The earlier
    design required signing off all 65 before any could be used, which front-loads
    judgement onto rubrics nobody has seen fail. A flag raised while marking a real
    answer carries far more information than an upfront pass does.

    Kept outside rubrics/ because that file is regenerated and gitignored.
    """
    if not FLAGS_FILE.exists():
        return {}
    data = json.loads(FLAGS_FILE.read_text())
    entries = data.get(str(year), {})
    return {k: v for k, v in entries.items() if isinstance(v, dict)}


def rubric_id(year: int, question: int) -> str:
    return f"{year}_Q{question}"


def question_anchors(page_anchors: list[str], answer_text: str) -> list[str]:
    """Narrow page-level anchors to the ones this question is actually about.

    Anchors are harvested per page, and a page carries several questions, so they
    leak: 2024 Q29 is about plant E and plant H but inherits "plant K" from Q30 and
    misses plant H entirely. Both consequences are bad -- the contextual gate would
    check for the wrong entity, and speech-to-text would not know to protect "plant
    H" from being heard as a word.

    The model answer names what the answer must operate on, so it decides. Anchors
    it never mentions are dropped, and anchors it mentions that the page scan missed
    are added.
    """
    from index_questions import ANCHOR_RE  # local import: keeps the CLI light

    text = answer_text.lower()
    kept = [a for a in page_anchors if a.lower() in text]
    seen = {a.lower() for a in kept}
    for noun, letter in ANCHOR_RE.findall(answer_text):
        anchor = f"{noun.lower()} {letter}"
        if anchor.lower() not in seen:
            seen.add(anchor.lower())
            kept.append(anchor)
    return sorted(kept)


def scaffold(year: int, questions_root: Path = WORK_QUESTIONS,
             answers_root: Path = WORK_ANSWERS,
             existing: dict | None = None) -> dict:
    from index_questions import verified_marks

    inventory = json.loads((questions_root / str(year) / "questions.json").read_text())
    answers = json.loads((answers_root / str(year) / "answers.json").read_text())
    verified = verified_marks(year)
    flags = flags_for(year)

    marks: dict[tuple[int, str | None], int | None] = {}
    anchors: dict[int, list[str]] = {}
    for entry in inventory["questions"]:
        anchors[entry["question"]] = entry.get("scenario_anchors", [])
        for part in entry["parts"]:
            if not part.get("is_parent"):
                marks[(entry["question"], part["part"])] = part["marks"]

    prior = {(r["question"], r["part"]): r for r in (existing or {}).get("rubrics", [])}

    rubrics: list[dict] = []
    for entry in answers["questions"]:
        question = entry["question"]
        for part in entry["parts"]:
            key = (question, part["part"])
            before = prior.get(key, {})
            # The answer extraction labels sub-parts more accurately than the
            # question inventory does — it nests 2024 Q30 as b(i)/b(ii) where the
            # inventory sees a single "b" — so a verified reading is consulted for
            # sub-parts the inventory never knew existed.
            allocation = verified.get(f"{question}{part['part'] or ''}")
            if allocation is None:
                allocation = marks.get(key)
            if allocation is None and part["part"] and "(" in part["part"]:
                # The answers nest a sub-part the inventory left bare: 2022 Q31 is
                # indexed "a" but answered as "a(i)". The allocation printed on the
                # paper belongs to that same sub-part under its shorter name.
                allocation = marks.get((question, part["part"].split("(")[0]))
            if allocation is None:
                allocation = marks.get((question, None))
            rubrics.append({
                "question_id": rubric_id(year, question),
                "question": question,
                "part": part["part"],
                "marks": allocation,
                "syllabus_era": "2023" if year >= SYLLABUS_2023_FROM else "pre-2023",
                "topics": before.get("topics", []),
                "themes": themes_for(before.get("topics", [])),
                "syllabus_topics": official_topics(before.get("topics", [])),
                "out_of_scope_from_2026": out_of_scope_from_2026(
                    before.get("topics", [])),
                "scenario_anchors": before.get("scenario_anchors") or question_anchors(
                    anchors.get(question, []),
                    f"{part['model_answer']} {part['explanation']}"),
                "response_mode": before.get("response_mode", "spoken"),
                "chains": before.get("chains", []),
                "chains_required": before.get("chains_required", 1),
                "traps": before.get("traps", []),
                "model_answer": part["model_answer"],
                "explanation": part["explanation"],
                "source": answers.get("source", "EPH suggested answer"),
                # Approved unless flagged.
                "flagged": bool(flags.get(f"{question}{part['part'] or ''}")),
                "flag_reason": (flags.get(f"{question}{part['part'] or ''}") or {})
                    .get("reason", ""),
                "reviewed": not flags.get(f"{question}{part['part'] or ''}"),
            })

    return {
        "year": year,
        "source": answers.get("source", "EPH suggested answer"),
        "ocr": answers.get("ocr"),
        "rubrics": rubrics,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--years", nargs="*", type=int)
    parser.add_argument("--questions-root", type=Path, default=WORK_QUESTIONS)
    parser.add_argument("--answers-root", type=Path, default=WORK_ANSWERS)
    parser.add_argument("--out", type=Path, default=RUBRIC_DIR)
    args = parser.parse_args(argv)

    years = args.years or sorted(int(p.name) for p in args.answers_root.iterdir()
                                 if p.is_dir() and p.name.isdigit())
    args.out.mkdir(parents=True, exist_ok=True)

    for year in years:
        target = args.out / f"{year}.json"
        existing = json.loads(target.read_text()) if target.exists() else None
        data = scaffold(year, args.questions_root, args.answers_root, existing)
        target.write_text(json.dumps(data, indent=2))
        stray = unmapped([t for r in data["rubrics"] for t in r["topics"]])
        if stray:
            print(f"    WARN topics with no syllabus theme: {stray}")
        retired = sorted({f"Q{r['question']}{r['part'] or ''}"
                          for r in data["rubrics"] if r["out_of_scope_from_2026"]})
        if retired:
            print(f"    NOTE out of scope from 2026 (Cells removed): {retired}")
        authored = sum(1 for r in data["rubrics"] if r["chains"])
        flagged = sum(1 for r in data["rubrics"] if r["flagged"])
        print(f"{year}: {len(data['rubrics'])} rubrics scaffolded, "
              f"{authored} with chains, {flagged} flagged -> {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
